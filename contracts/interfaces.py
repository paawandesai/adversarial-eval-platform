# contracts/interfaces.py — the shared surface every agent codes against.
from __future__ import annotations
from typing import Protocol, Callable, Optional
from contracts.contracts import (
    AttackCase, AttackRun, JudgeVerdict, VulnerabilityReport, WorkItem,
    Verdict, OracleType,
)

class Store(Protocol):
    def add_case(self, case: AttackCase) -> None: ...
    def get_case(self, case_id: str) -> AttackCase: ...
    def list_cases(self, category: Optional[str] = None,
                   in_regression: Optional[bool] = None) -> list[AttackCase]: ...
    def add_run(self, run: AttackRun) -> None: ...
    def get_run(self, run_id: str) -> AttackRun: ...
    def add_verdict(self, verdict: JudgeVerdict) -> None: ...
    def list_verdicts(self, case_id: Optional[str] = None,
                      verdict: Optional[Verdict] = None) -> list[JudgeVerdict]: ...
    def add_report(self, report: VulnerabilityReport) -> None: ...
    def list_reports(self) -> list[VulnerabilityReport]: ...
    def coverage(self) -> dict: ...   # {category: {count, pass, fail, partial, cost_usd}}

class TargetClientProtocol(Protocol):        # the ATTACKER's view — public interface only
    async def authenticate(self, role: str) -> None: ...
    async def chat(self, messages: list[dict], conversation_id: Optional[str] = None) -> dict: ...
    async def upload(self, patient_id: str, file_path: str, doc_type: str) -> dict: ...
    async def pre_visit_brief(self, patient_id: str) -> dict: ...

class AuditReaderProtocol(Protocol):         # JUDGE-ONLY grey-box read. Red Team must NEVER import.
    async def tool_calls(self, correlation_id: str) -> list[dict]: ...
    async def response_trace(self, correlation_id: str) -> dict: ...

# Oracle: pure fn. Returns (Verdict, evidence) or None if this oracle doesn't apply to the case.
Oracle = Callable[[AttackCase, AttackRun, Optional[list[dict]]], Optional[tuple["Verdict", dict]]]

class Tracer(Protocol):
    def trace(self, correlation_id: str, step: str): ...   # context manager